import assert from 'node:assert/strict';
import { createConfigPackageFromCurrentProject } from '../../src/configStudio/legacyProjectAdapter';
import { evaluateV3WorkflowOutputs, validateV3WorkflowInputs } from '../../src/configStudio/V3WorkflowRunner';
import { validateWorkflowDefinition } from '../../src/configStudio/runtime';
import { canonicalizeWorkflow } from '../../src/configStudio/V3WorkflowEditor';
const config = createConfigPackageFromCurrentProject();
const workflow = config.workflows.find(item => item.id === 'v3-tpp_teleport')!;
const output = workflow.outputs[0];
const form = workflow.steps.find(step => step.kind === 'form')!;
const byTarget = (target: string) => output.assignments.find(assignment => assignment.target === target)!.expression;
const slots: Record<string, unknown> = { actor: 'capture-author', [byTarget('Name')]: 'Captured teleport', SOURCE_POINT: { x: 20, z: 13 }, TARGET_POINT: { x: 75, z: -18 }, SOURCE_ELEVATION: 0, TARGET_ELEVATION: 32 };
const abbreviation = form.controls!.find(control => control.id.includes('-abbr-'))!;
slots[abbreviation.slot!] = 'CAPTURE';
const classifications = { [output.id]: { class: 'TPP', kind: 'NOM', skind: 'NOM' } };
const options = { config, classifications, world: 'zth', coordinates: { [output.id]: [{ x: 20, y: -64, z: 13 }] }, now: new Date('2026-10-07T00:00:00Z') };
assert.ok(validateWorkflowDefinition(workflow, config).valid);
const record = evaluateV3WorkflowOutputs(workflow, slots, options)[0].record;
assert.deepEqual(record.TGTcoordinate, { x: 75, y: 32, z: -18 });
assert.equal(record.elevation, 0); assert.equal(record.TGTelevation, 32);
assert.deepEqual(record.CoordP, [[20,-64,13]]);
const knownY = evaluateV3WorkflowOutputs(workflow, { ...slots, SOURCE_POINT: { x:20, y:64, z:13 }, TARGET_POINT: { x:75, y:83, z:-18 } }, options)[0].record;
assert.equal(knownY.elevation, 64); assert.equal(knownY.TGTelevation, 83);
const warp = evaluateV3WorkflowOutputs(workflow, { ...slots, [byTarget('TGTWarp')]: 'WRP-I2D', TARGET_POINT: { x:75, y:83, z:-18 } }, options)[0].record;
assert.equal(warp.TGTcoordinate, undefined); assert.equal(warp.TGTelevation, undefined);
assert.ok(validateV3WorkflowInputs(workflow, { ...slots, TARGET_POINT: undefined }).some(issue => issue.message.includes('目标点')));
assert.ok(!validateV3WorkflowInputs(workflow, { ...slots, TARGET_POINT: undefined, [byTarget('TGTWarp')]: 'WRP-I2D' }).some(issue => issue.message.includes('目标点')));
const canonical = canonicalizeWorkflow(workflow, config);
assert.deepEqual(canonical.steps.at(-1)?.drawing?.auxiliaryPoints, workflow.steps.at(-1)?.drawing?.auxiliaryPoints);
assert.deepEqual(canonical.steps.at(-1)?.controls, workflow.steps.at(-1)?.controls);
const invalid = structuredClone(workflow); invalid.steps.at(-1)!.drawing!.auxiliaryPoints![0].slot = 'SOURCE_POINT';
assert.equal(validateWorkflowDefinition(invalid, config).valid, false);
const self = structuredClone(workflow); self.outputs[0].assignments.unshift({ id: 'self-final-id', target: 'tags.self', expression: 'ID_1' });
assert.equal((evaluateV3WorkflowOutputs(self, slots, options)[0].record.tags as any).self, record.ID);
console.log('workflow-capture: optional Y, source/target isolation, conditional Warp path, preserved drawing controls and final self-ID: OK');
