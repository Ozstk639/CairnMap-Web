import assert from 'node:assert/strict';
import { LabelDensityLimiter, resolveLabelDensityConfig } from '../../src/components/Rules/rendering/label/labelDensity';
import { LabelPlacementCache, resolveLabelPlacementCacheConfig } from '../../src/components/Rules/rendering/label/labelPlacementCache';
const rect = { x: 10, y: 10, w: 20, h: 10 };
const limiter = new LabelDensityLimiter();
const ordinary = resolveLabelDensityConfig({ densityEnabled: true, densityMaxLabelsPerGrid: 1 })!;
limiter.commit(rect, ordinary);
assert.equal(limiter.canPlace(rect, ordinary), false);
assert.equal(limiter.canPlace(rect, { ...ordinary, selected: true }), true);
assert.equal(limiter.canPlace(rect, { ...ordinary, selected: true, preserveSelected: false }), false);
assert.equal(limiter.canPlace(rect, { ...ordinary, collisionRole: 'required' }), true);
assert.equal(limiter.canPlace(rect, { ...ordinary, collisionRole: 'required', preserveRequired: false }), false);
const input = { id: 'a', text: 'old', placement: 'center' as const, zoom: 2, worldId: 'w1', displayMode: 'normal', geometrySignature: '[1,2]', placementCacheEnabled: true, placementCacheKey: 'featureID' as const, placementInvalidateWhen: ['worldChanged', 'featureGeometryChanged', 'featureTextChanged', 'modeChanged', 'collisionFailedRepeatedly', 'labelOutOfViewport'] };
const config = resolveLabelPlacementCacheConfig(input)!;
for (const delta of [{ worldId: 'w2' }, { displayMode: 'floor' }, { geometrySignature: '[2,3]' }, { text: 'new' }]) assert.notEqual(resolveLabelPlacementCacheConfig({ ...input, ...delta })?.key, config.key);
assert.equal(resolveLabelPlacementCacheConfig({ ...input, text: 'new', placementInvalidateWhen: [] })?.key, resolveLabelPlacementCacheConfig({ ...input, placementInvalidateWhen: [] })?.key);
const cache = new LabelPlacementCache();
cache.commit(config, { anchorIndex: 2, candidateName: 'N' });
cache.noteFailure(config, 'collisionLabel'); cache.noteFailure(config, 'collisionLabel');
assert.ok(cache.get(config));
cache.noteFailure(config, 'collisionLabel'); assert.equal(cache.get(config), undefined);
cache.commit(config, { anchorIndex: 1, candidateName: 'C' });
cache.noteFailure(config, 'viewport'); assert.equal(cache.get(config), undefined);
console.log('density-stability: budgets, selected/required opt-out and real cache invalidation: OK');
