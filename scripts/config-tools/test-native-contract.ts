import assert from 'node:assert/strict';
import { createBlankV32Package, createDefaultGeometryProfile } from '../../src/configStudio/v32Defaults';
import { readConfigPackage } from '../../src/configStudio/package';
import { validateConfigPackage } from '../../src/configStudio/runtime';
import { resolveConfigRuntimeRule } from '../../src/components/Rules/configRuntime/configPackageAdapter';

const config = createBlankV32Package();
const profile = createDefaultGeometryProfile('Point');
profile.zoomPriority.rules[0].representation = 'labelOnly';
config.nodes.push({ nodeId: 'native-label-only', path: { class: 'NEW' }, children: [], fields: [], geometryType: 'Point', geometryProfiles: { Point: profile } });
assert.equal(config.contractRevision, 6);
assert.equal(validateConfigPackage(config).valid, true);
const feature: any = { uid: 'new', type: 'Points', p3: { x: 0, y: -64, z: 0 }, featureInfo: { ID: 'new', Name: 'Label', World: 'zth', Class: 'NEW' }, meta: { Class: 'NEW', Type: 'Points', World: 'zth', idValue: 'new', sig: {} } };
const ctx: any = { worldId: 'zth', leafletZoom: 3, zoomLevel: 6, inFloorView: false };
const rule: any = resolveConfigRuntimeRule(config, feature, ctx, null);
assert.equal(rule.symbol.labelClick.mode, 'labelOnly');
assert.equal(rule.display.geometry.render, 'none');
assert.equal(rule.symbol.label.enabled, true);
const older = structuredClone(config);
older.contractRevision = 5;
older.nodes[0].geometryProfiles.Point!.zoomPriority.rules[0].representation = 'geometry';
const sourceRule = older.nodes[0].geometryProfiles.Point!.zoomPriority.rules[0];
sourceRule.label!.collision.basePriority = 25;
sourceRule.priority = { mode: 'add', base: 30 };
const loaded = await readConfigPackage(new File([JSON.stringify(older)], 'r5.json'));
assert.equal(loaded.contractRevision, 6);
assert.equal(loaded.nodes[0].geometryProfiles.Point!.zoomPriority.rules[0].label!.collision.basePriority, 55);
assert.equal(sourceRule.label!.collision.basePriority, 25, 'Migration mutated its input');
await assert.rejects(() => readConfigPackage(new File([JSON.stringify({ ...config, contractRevision: 99 })], 'future.json')));
assert.equal(validateConfigPackage({ ...config, contractRevision: 99 } as any).valid, false);
console.log('native-contract: r6 labelOnly and non-mutating r5 upgrade, unknown revision rejection: OK');

const dynamic = structuredClone(older);
const dynamicRule = dynamic.nodes[0].geometryProfiles.Point!.zoomPriority.rules[0];
dynamicRule.priority = { mode: 'replace', base: 100, metric: { kind: 'field', field: 'score', multiplier: 2, rounding: 'floor' } };
dynamicRule.conditionalOverrides = [{ id: 'authored-branch', when: [{ kind: 'fieldEquals', field: 'Name', value: 'branch' }], label: { ...dynamicRule.label!, collision: { ...dynamicRule.label!.collision, basePriority: 40 } } }];
const upgraded = await readConfigPackage(new File([JSON.stringify(dynamic)], 'dynamic-r5.json'));
assert.equal(upgraded.nodes[0].geometryProfiles.Point!.zoomPriority.rules[0].label!.collision.basePriority, 25, 'replace metric cannot add C base during upgrade');
const branchFeature = { ...feature, featureInfo: { ...feature.featureInfo, Name: 'branch', score: 5 } };
const branchRule: any = resolveConfigRuntimeRule(upgraded, branchFeature, ctx, null);
assert.equal(branchRule.display.collision.priority, 50, 'authored r5 conditional B + dynamic C retained');
console.log('native-contract: r5 replace metrics and conditional B/C semantics retained: OK');
