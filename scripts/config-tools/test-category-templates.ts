import assert from 'node:assert/strict';
import { createEditableConfigPackageFromCurrentProject } from '../../src/configStudio/renderRuleTemplates';
import { compatibleCategoryTemplates, createCategoryFromTemplate } from '../../src/configStudio/categoryTemplates';
import { resolveGeometryProfile, resolveEffectiveFields, validateConfigPackage } from '../../src/configStudio/runtime';
const config = createEditableConfigPackageFromCurrentProject();
const parent = config.nodes.find(n => n.path.class === 'ROD' && !n.path.kind)!;
const profile = resolveGeometryProfile(config, parent.path, 'LineString')!;
const request = { parentId: parent.nodeId, code: 'TEST', geometry: 'LineString' as const, allowMultipleParts: profile.allowMultipleParts, anchor: profile.anchor ?? 'featureBbox' as const };
const original = structuredClone(config);
const inherited = createCategoryFromTemplate(config, request);
assert.equal(inherited.node.geometryProfiles.LineString, undefined);
assert.deepEqual(resolveGeometryProfile(inherited.config, inherited.node.path, 'LineString'), profile);
assert.deepEqual(resolveEffectiveFields(inherited.config, inherited.node.path), resolveEffectiveFields(config, parent.path));
assert.deepEqual(config, original);
const candidates = compatibleCategoryTemplates(config, request);
assert(candidates.every((item, index) => !index || candidates[index-1].rank <= item.rank));
const source = candidates.find(item => item.rank === 0) ?? candidates[0]; assert(source);
const copied = createCategoryFromTemplate(config, { ...request, sourceId: source.node.nodeId });
const rules = copied.node.geometryProfiles.LineString!.zoomPriority.rules;
assert.notEqual(rules[0].id, source.profile.zoomPriority.rules[0].id);
assert.deepEqual(rules.map(rule => rule.when), source.profile.zoomPriority.rules.map(rule => rule.when));
assert.equal(copied.node.fields.length, 0); assert.equal(copied.node.card, undefined); assert.equal(copied.config.workflows.length, config.workflows.length);
rules[0].label!.visible = !rules[0].label!.visible; assert.deepEqual(config, original);
assert.throws(() => createCategoryFromTemplate(config, { ...request, geometry: 'Point' }));
assert.throws(() => createCategoryFromTemplate(config, { ...request, allowMultipleParts: !profile.allowMultipleParts, sourceId: source.node.nodeId }));
const disabled = structuredClone(config); disabled.nodes.find(n => n.nodeId === parent.nodeId)!.inheritDown!.display = false;
assert(createCategoryFromTemplate(disabled, request).node.geometryProfiles.LineString);
assert(validateConfigPackage(inherited.config).valid);
console.log('category-templates: parent propagation, capability filtering, sibling rank, full condition/order snapshots, isolated identities and source immutability: OK');
