import assert from 'node:assert/strict';
import { createConfigPackageFromCurrentProject } from '../../src/configStudio/legacyProjectAdapter';
import { nextWorkflowSlot, workflowControlFromField } from '../../src/configStudio/workflowFieldControl';
import { evaluateV3WorkflowOutputs, validateV3WorkflowInputs } from '../../src/configStudio/V3WorkflowRunner';
import { canonicalizeWorkflow } from '../../src/configStudio/V3WorkflowEditor';
import { validateWorkflowDefinition } from '../../src/configStudio/runtime';
import type { FieldDefinition } from '../../src/configStudio/types';
const config = createConfigPackageFromCurrentProject();
const workflow = structuredClone(config.workflows.find(item => item.id === 'v3-wrp_warp')!);
const field: FieldDefinition = { fieldId:'new-field', key:'tags.customValues', type:'number', input:'text', cardinality:'multiple', required:false, labels:{zh:'新值',en:''},description:{zh:'',en:''},defaultValue:[1,2],placeholder:'输入数值' };
config.nodes.find(node => node.path.class==='WRP'&&!node.path.kind)!.fields.push(field);
const control=workflowControlFromField(field,nextWorkflowSlot(workflow),'new-input');
assert.equal(control.kind,'group');assert.equal(control.group!.storage,'scalar');assert.equal(control.group!.itemFields[0].kind,'number');
assert.deepEqual(control.defaultValue,[1,2]);
const form=workflow.steps.find(step=>step.kind==='form')!;form.controls!.push(control);
workflow.outputs[0].assignments.push({id:'new-binding',target:field.key,expression:control.slot!});
const saved=canonicalizeWorkflow(workflow,config);
assert.equal(validateWorkflowDefinition(saved,config).valid,true);
assert.equal(validateV3WorkflowInputs(saved,{[control.slot!]:[3,4]},[{...form,controls:[control]}],config).length,0);
const output=evaluateV3WorkflowOutputs(saved,{[control.slot!]:[3,4]})[0];
assert.deepEqual((output.record.tags as any).customValues,[3,4]);
assert.throws(()=>workflowControlFromField({...field,scenes:{workflow:false}},'X','off'));
assert.throws(()=>workflowControlFromField({...field,key:'World'},'X','protected'));
const reference=workflowControlFromField({...field,key:'tags.ref',cardinality:'single',input:'featureSearch',reference:{classCode:'BUD',matchField:'ID',displayField:'Name'}},'REF','reference');
assert.equal(reference.search!.returnField,'ID');assert.deepEqual(reference.search!.queryFields,['ID','Name']);
const many=structuredClone(workflow);many.steps=[{id:'many',kind:'form',label:{zh:'多输入',en:''},controls:Array.from({length:26},(_,index)=>({...control,id:String(index),slot:String.fromCharCode(65+index)}))}];
assert.equal(nextWorkflowSlot(many),'SLOT_1');
console.log('workflow-field-controls: field input/type/default/options/reference/scenes, scalar arrays, real bindings and slots beyond Z: OK');

config.registries.optionSets!.push({id:'multi-options',label:{zh:'选项',en:''},options:[{value:'stored',label:{zh:'显示',en:''}}]});
const multipleSelect=workflowControlFromField({...field,input:'select',type:'enum',defaultValue:['stored'],optionSource:{registryKey:'multi-options'}},'ENUM','multiple-select',config);
assert.deepEqual(multipleSelect.group!.itemFields[0].options,[{value:'stored',label:{zh:'显示',en:''}}]);
