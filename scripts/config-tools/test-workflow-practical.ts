import assert from 'node:assert/strict';
import { createConfigPackageFromCurrentProject } from '../../src/configStudio/legacyProjectAdapter';
import { canonicalizeWorkflow } from '../../src/configStudio/V3WorkflowEditor';
import { evaluateV3WorkflowOutputs, validateV3WorkflowInputs, findV3SearchCandidates } from '../../src/configStudio/V3WorkflowRunner';
import { validateWorkflowDefinition } from '../../src/configStudio/runtime';
const config = createConfigPackageFromCurrentProject();
const road = config.workflows.find(workflow => workflow.id === 'v3-rod_road')!;
const two = structuredClone(road);
two.outputs[0].assignments = [{ id: 'first-id', target: 'ID', expression: '"FIRST"' }];
two.outputs.push({ ...structuredClone(two.outputs[0]), id: 'second', assignments: [{ id: 'second-id', target: 'ID', expression: '"SECOND"' }, { id: 'parent', target: 'tags.parent', expression: 'ID_1' }] });
const canonical = canonicalizeWorkflow(two, config);
assert.equal(validateWorkflowDefinition(canonical, config).valid, true);
assert.equal((evaluateV3WorkflowOutputs(canonical, {})[1].record.tags as any).parent, 'FIRST');
const forward = structuredClone(canonical);
forward.outputs[0].assignments = [{ id: 'derived-id', target: 'ID', expression: 'ID_2+"-CHILD"' }];
forward.outputs[1].assignments = [{ id: 'parent-id', target: 'ID', expression: '"PARENT"' }];
assert.equal(evaluateV3WorkflowOutputs(forward, {})[0].record.ID, 'PARENT-CHILD');
forward.outputs[1].assignments = [{ id: 'cycle', target: 'ID', expression: 'ID_1' }];
assert.equal(validateWorkflowDefinition(forward, config).valid, false);
assert.throws(() => evaluateV3WorkflowOutputs(forward, {}), /循环/);
const illegal = structuredClone(road);
illegal.outputs[0].assignments.push({ id: 'illegal', target: 'Class', expression: '"UNKNOWN_CLASS"' });
assert.equal(validateWorkflowDefinition(illegal, config).valid, false);
assert.throws(() => evaluateV3WorkflowOutputs(illegal, {}), /系统字段/);
assert.ok(validateV3WorkflowInputs(road, {}, [road.steps[0]]).length);
assert.equal(validateV3WorkflowInputs(road, { actor: 'tester' }, [road.steps[0]]).length, 0);
const group = structuredClone(road.steps.flatMap(step => step.controls ?? []).find(control => control.kind === 'group')!);
group.required = false; group.group!.optional = false; delete group.group!.minItems;
assert.ok(validateV3WorkflowInputs(road, { [group.slot!]: [] }, [{ id: 'group', kind: 'form', label: { zh: '组', en: '' }, controls: [group] }]).length);
const drawing = structuredClone(road);
drawing.steps.find(step => step.kind === 'geometry')!.drawing = { allowBack: false, keepDrawingWhenBack: false };
assert.equal(canonicalizeWorkflow(drawing, config).steps.find(step => step.kind === 'geometry')!.drawing?.allowBack, false);
assert.equal(canonicalizeWorkflow(drawing, config).steps.find(step => step.kind === 'geometry')!.drawing?.keepDrawingWhenBack, false);
const search = road.steps.flatMap(step => step.controls ?? []).find(control => control.search)!.search!;
const records = [{ ID: 'a', Name: 'match', Class: search.target.class, Kind: search.target.kind, World: 'zth' }, { ID: 'b', Name: 'match', Class: search.target.class, Kind: search.target.kind, World: 'naraku' }];
assert.equal(findV3SearchCandidates(records, { ...search, cacheScope: 'world' }, 'match', 'zth').length, 1);
assert.equal(findV3SearchCandidates(records, { ...search, cacheScope: 'loadedWorlds' }, 'match', 'zth').length, 2);
console.log('workflow-practical: final-ID graph, protected classification, actor/group constraints, drawing options and world scopes: OK');
