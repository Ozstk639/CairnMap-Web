import assert from 'node:assert/strict';
import { createEditableConfigPackageFromCurrentProject } from '../../src/configStudio/renderRuleTemplates';
import { resolveSelectableFields, validateConfigPackage, validateWorkflowDefinition } from '../../src/configStudio/runtime';
import { importFieldIntoControl, resolveImportedControl, markFieldOverrides, fieldImportErrors, resolveWorkflowFields } from '../../src/configStudio/fieldReuse';
import { buildV3CardSections } from '../../src/configStudio/V3CardRenderer';
import { evaluateV3WorkflowOutputs } from '../../src/configStudio/V3WorkflowRunner';
import { migrateFieldsToR8 } from '../../src/configStudio/fieldMigration';
import type { FieldDefinition, WorkflowControl } from '../../src/configStudio/types';
const config=createEditableConfigPackageFromCurrentProject();
assert.equal(config.contractRevision,8);assert.equal(config.registries.optionSets,undefined);
assert.equal(validateConfigPackage(config).valid,true);
assert(resolveSelectableFields(config,{class:'PFB'}).some(field=>field.key==='LineID'));
assert(!resolveSelectableFields(config,{class:'RLE'}).some(field=>field.key==='LineID'));
assert(!resolveSelectableFields(config,{class:'WRP'}).some(field=>['ModifiedBy','Skind','Skind2'].includes(field.key)));
const root=config.nodes.find(node=>node.path.class==='WRP'&&!node.path.kind)!;
const field:FieldDefinition={fieldId:'status-definition',key:'tags.status',type:'enum',cardinality:'single',input:'select',options:[{value:'0',label:{zh:'关闭',en:''}},{value:'1',label:{zh:'开启',en:'On'}}],optionValueType:'number',defaultValue:0,labels:{zh:'状态',en:''},description:{zh:'',en:''}};
root.fields.push(field);
const workflow=structuredClone(config.workflows.find(workflow=>workflow.id==='v3-wrp_warp')!);
const original:WorkflowControl={id:'status-input',slot:'STATUS',columns:1,kind:'text',label:{zh:'原输入',en:''}};
const imported=importFieldIntoControl(config,workflow,original,root.nodeId,field);
workflow.steps.find(step=>step.kind==='form')!.controls!.push(imported);
workflow.outputs[0].assignments.push({id:'status-binding',target:field.key,expression:'STATUS'});
assert.equal(imported.id,original.id);assert.equal(imported.slot,original.slot);assert.equal(imported.defaultValue,0);
field.labels.zh='更新状态';
assert.equal(resolveImportedControl(config,workflow,imported).label.zh,'更新状态');
const override=markFieldOverrides(imported,{...imported,label:{zh:'自定',en:''}});
assert.equal(resolveImportedControl(config,workflow,override).label.zh,'自定');
field.cardinality='multiple';assert(fieldImportErrors(config,workflow,imported).some(message=>message.includes('值数量')));
assert(!validateWorkflowDefinition(workflow,config).valid);field.cardinality='single';
const invalid=markFieldOverrides(imported,{...imported,options:[{value:'2',label:{zh:'非法',en:''}}]});
workflow.steps.find(step=>step.kind==='form')!.controls=workflow.steps.find(step=>step.kind==='form')!.controls!.map(control=>control.id===invalid.id?invalid:control);
assert(validateWorkflowDefinition(workflow,config).issues.some(issue=>issue.code==='field-import-target-conflict'));
workflow.steps.find(step=>step.kind==='form')!.controls=workflow.steps.find(step=>step.kind==='form')!.controls!.map(control=>control.id===invalid.id?imported:control);
const output=evaluateV3WorkflowOutputs(resolveWorkflowFields(config,workflow),{STATUS:'0'})[0];
assert.equal((output.record.tags as Record<string,unknown>).status,0);
root.card={mode:'fields',items:[{id:'status-card',source:field.key,visible:true,renderer:'text',labelMode:'field',valueMode:'field'}]};
const record:any={featureInfo:{Class:'WRP',tags:{status:0}},meta:{Class:'WRP'}};
assert.deepEqual(buildV3CardSections(config,record)?.mainRows[0],{label:'更新状态',value:'关闭'});
root.card.items[0].labelMode='override';root.card.items[0].label={zh:'本地标题',en:''};
assert.equal(buildV3CardSections(config,record)?.mainRows[0].label,'本地标题');
assert.equal(migrateFieldsToR8(config).registries.optionSets,undefined);
console.log('field-reuse-r8: lossless options, metadata boundary, PFB LineID, follow/override, type and target conflicts, numeric enum output and actual card mapping: OK');
